#!/usr/bin/env python3
"""Regenerate the mnPaper icon pixels from the mn-brand 2048x2048 render.

    python3 gen_icon_tables.py <mnpaper-2048.png> --header icon_tables.h
    python3 gen_icon_tables.py <mnpaper-2048.png> --ico OUT.ico

The source is the mn-brand pipeline's `icons/mnpaper.png` (2048x2048), which
lives in the mnbrand repository, not here - this repo ships only the baked
results, so regeneration needs that checkout.

The header is always written to the --header path (default icon_tables.h
in the current directory); --ico additionally writes a multi-size .ico.
Both outputs come from the same pipeline, so the tray tables and every .ico
entry are the same pixels by construction. Needs Pillow (`pip install
Pillow`) and nothing else; neither artifact is generated at build time,
both are committed.

What this does to the artwork (and what it deliberately does NOT do):

- Crops to the brand card's outer edge (its 1.5-unit white stroke included).
  The card's stroke-center rectangle is exactly 277x270 units at (11,12) in
  the 300-unit mn master viewBox; at the render's 2048/300 scale that is
  1891x1843 px, and the stroke-outer box around it is x 70..1971, y 76..1930
  (CARD_BOX below, 1901x1854 px), which is what gets cropped.
- Fits the card into a square canvas with transparent top/bottom padding
  (~1.2% of the edge each) instead of cropping into the stroke.
- Clips to the brand corner radius, r = 43/277 of the icon edge (~15.5%),
  with a 4x4 supersampled alpha mask. Outside the card only alpha changes;
  NO pixel inside the card is altered. This is a presentation clip done at
  swap time, not a mn-brand edit: the artwork itself still changes only in
  the mn-brand pipeline. See mnbrand docs/icon-corner-radius.md.

Never derive these pixels from the 300x300 control copy in
mnbrand/reference/originals - that is an audit control, not a source.
"""

import argparse
import sys

from PIL import Image

SIZES_SNI = [16, 24, 32, 48, 64, 128]           # what the tray serves
SIZES_ICO = [16, 24, 32, 48, 64, 128, 256]      # what the exe embeds

# Stroke-outer card box in the 2048 render (see module docstring).
CARD_BOX = (70, 76, 1971, 1930)                 # PIL crop box: x0, y0, x1, y1
RX, CARD_W = 43, 277                            # master-units radius / width


def rounded_alpha(w, h, x0, y0, cw, ch, radius):
    """4x4-supersampled rounded-rect alpha for a (cw,ch) rect at (x0,y0)."""
    a = bytearray(w * h)
    for y in range(y0, y0 + ch):
        for x in range(x0, x0 + cw):
            hit = 0
            for sy in range(4):
                py = y + (sy + 0.5) / 4.0
                dy = max(abs(py - (y0 + ch / 2.0)) - (ch / 2.0 - radius), 0.0)
                for sx in range(4):
                    px = x + (sx + 0.5) / 4.0
                    dx = max(abs(px - (x0 + cw / 2.0)) - (cw / 2.0 - radius), 0.0)
                    if dx * dx + dy * dy <= radius * radius:
                        hit += 1
            a[y * w + x] = round(255 * hit / 16)
    return a


def render(src, size):
    card = src.crop(CARD_BOX)
    k = size / card.width
    h2 = round(card.height * k)
    rgb = card.resize((size, h2), Image.Resampling.LANCZOS).convert("RGBA")
    canvas = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    canvas.paste(rgb, (0, (size - h2) // 2))
    r = size * RX / CARD_W                       # keep fractional; mask is AA
    alpha = rounded_alpha(size, size, 0, (size - h2) // 2, size, h2, r)
    canvas.putalpha(Image.frombytes("L", (size, size), bytes(alpha)))
    return canvas


def emit_header(images, path):
    out = ["/*",
           " * linux/icon_tables.h - the mnPaper tray icon, generated.",
           " *",
           " * Generated by linux/gen_icon_tables.py from the mn-brand 2048x2048",
           " * mnpaper render: card crop, square-fit, rounded corner at the brand",
           " * radius 43/277 of the edge. DO NOT HAND-EDIT - regenerate and commit.",
           " * The tray serves all of these sizes so the panel never upscales",
           " * (a lone 24x24 pixmap was smoothed 2x on this scale-2 panel).",
           " *",
           " * D-Bus ARGB32 is big-endian per pixel: bytes are A, R, G, B.",
           " */",
           "#ifndef MNPAPER_ICON_TABLES_H",
           "#define MNPAPER_ICON_TABLES_H", ""]
    for s, im in images:
        px = im.load()
        out.append("static const unsigned char ICON_%d[%d * %d * 4] = {" % (s, s, s))
        for y in range(s):
            row = []
            for x in range(s):
                r, g, b, a = px[x, y]
                row.append("%d,%d,%d,%d" % (a, r, g, b))
            for i in range(0, s, 16):
                out.append("    " + " ".join(b + "," for b in row[i:i + 16]))
        out.append("};")
        out.append("")
    out.append("struct ICON_SIZE { int w; const unsigned char *argb; };")
    out.append("")
    out.append("#define ICON_SIZES_N %d" % len(images))
    out.append("static const struct ICON_SIZE ICON_SIZES[ICON_SIZES_N] = {")
    for s, _ in images:
        out.append("    { %d, ICON_%d }," % (s, s))
    out.append("};")
    out.append("")
    out.append("#endif")
    open(path, "w").write("\n".join(out) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("source")
    ap.add_argument("--ico", help="also write a multi-size .ico here")
    ap.add_argument("--header", default="icon_tables.h")
    args = ap.parse_args()

    src = Image.open(args.source).convert("RGB")
    sni = [(s, render(src, s)) for s in SIZES_SNI]
    emit_header(sni, args.header)

    if args.ico:
        ico_all = [(s, render(src, s)) for s in SIZES_ICO]
        big = ico_all[-1][1]
        others = [im for s, im in ico_all[:-1]]
        big.save(args.ico, format="ICO",
                 append_images=others,
                 sizes=[(s, s) for s in SIZES_ICO])
    print("wrote %s%s" % (args.header,
                          " and " + args.ico if args.ico else ""),
          file=sys.stderr)


if __name__ == "__main__":
    main()
